QAPI = "https://api.quran.com/api/v4"

def get(url):
    return json.load(urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"}), timeout=60))

def letters(t):
    t = t.replace("ﷺ", "صلى الله عليه وسلم")
    t = "".join(c for c in t if not unicodedata.category(c).startswith("M")).replace("ٱ", "ا").replace("ـ", "")
    return " ".join(re.sub(r"[^\u0621-\u064A ]", " ", t).split())

